"""AI-powered policy.yaml generation from compliance documents.

Given one or more compliance documents (Markdown, text, PDF, YAML, JSON),
extracts governance rules and maps them to ResearchForge's PolicySpec schema,
writing a validated .researchforge/policy.yaml with inline comments that
cite the source document sections.

Without an AI provider: writes a safe minimal policy from repo heuristics.
With an AI provider:   reads the documents and produces a fully mapped policy.

Supports PDF reading when pypdf or pdfplumber is installed; gracefully falls
back to a clear error message when neither is available.
"""

from __future__ import annotations

import contextlib
import textwrap
from pathlib import Path

import yaml

from researchforge.ai.providers import AiProvider
from researchforge.ai.usage import purpose

# ── document reading ─────────────────────────────────────────────────────────

SUPPORTED_TEXT_SUFFIXES = {".md", ".txt", ".rst", ".yaml", ".yml", ".json", ".toml"}
SUPPORTED_PDF_SUFFIX = ".pdf"
_MAX_DOC_CHARS = 60_000  # keep prompts within token budgets


def _read_pdf(path: Path) -> str:
    """Extract text from a PDF. Tries pypdf then pdfplumber."""
    try:
        import pypdf  # type: ignore[import-not-found]

        reader = pypdf.PdfReader(str(path))
        pages = [page.extract_text() or "" for page in reader.pages]
        return "\n\n".join(pages)
    except ImportError:
        pass

    try:
        import pdfplumber  # type: ignore[import-not-found]

        with pdfplumber.open(str(path)) as pdf:
            pages = [page.extract_text() or "" for page in pdf.pages]
        return "\n\n".join(pages)
    except ImportError:
        pass

    raise RuntimeError(
        f"Cannot read {path.name}: PDF extraction requires pypdf or pdfplumber.\n"
        "Install one:  pip install pypdf   or   pip install pdfplumber\n"
        "Or convert the PDF to text/Markdown first."
    )


def read_document(path: Path) -> str:
    """Read a single compliance document and return its text."""
    suffix = path.suffix.lower()
    if suffix == SUPPORTED_PDF_SUFFIX:
        text = _read_pdf(path)
    elif suffix in SUPPORTED_TEXT_SUFFIXES:
        text = path.read_text(encoding="utf-8", errors="replace")
    else:
        raise ValueError(
            f"Unsupported file type: {path.suffix}. "
            f"Supported: {', '.join(sorted(SUPPORTED_TEXT_SUFFIXES | {SUPPORTED_PDF_SUFFIX}))}"
        )
    return text[:_MAX_DOC_CHARS]


def collect_documents(source: Path) -> list[tuple[Path, str]]:
    """Collect (path, text) pairs from a file or directory."""
    if source.is_file():
        return [(source, read_document(source))]

    docs: list[tuple[Path, str]] = []
    all_suffixes = SUPPORTED_TEXT_SUFFIXES | {SUPPORTED_PDF_SUFFIX}
    for p in sorted(source.rglob("*")):
        if p.is_file() and p.suffix.lower() in all_suffixes:
            with contextlib.suppress(ValueError, RuntimeError):
                docs.append((p, read_document(p)))
    if not docs:
        raise ValueError(
            f"No readable compliance documents found in {source}. "
            f"Supported formats: {', '.join(sorted(all_suffixes))}"
        )
    return docs


# ── heuristic fallback (no AI) ───────────────────────────────────────────────

_MINIMAL_POLICY_TEMPLATE = """\
# ResearchForge policy — generated by `researchforge generate policy`
# Edit the values below to match your organization's requirements.
# Run `researchforge compliance policy-validate` after editing.
#
# Source documents: {source_note}

version: 1

# Files that experiments are never allowed to modify.
# The evaluator and compliance docs are always a good start.
protected_files:
{protected_files_yaml}

# Which AI providers experiments may use.
# Leave both lists empty to allow any provider.
models:
  allowed_providers: []   # e.g. [anthropic, azure_openai]
  denied_providers: []    # e.g. [unapproved_external_provider]

# Shipping controls.
shipping:
  human_approval_required: false  # set true for team / regulated environments
  require_clean_worktree: true
  require_all_blocking_gates: true

# Security scans (required | optional | disabled).
security:
  secret_scan: optional
  dependency_scan: optional
  sbom: optional
  provenance: optional
  vulnerabilities:
    block_severity: [critical]

# Network egress policy.
network:
  default: allow
  allowed_domains: []     # e.g. [arxiv.org, api.openai.com]

# Data access boundaries.
data:
  pii_allowed: true
  secrets_allowed: false
  denied_data_paths: []   # e.g. [data/private/**, secrets/**]
"""


def _guess_protected_files(repo_root: Path) -> list[str]:
    candidates = [
        "benchmarks/evaluate.py",
        "benchmarks/",
        ".researchforge/policy.yaml",
        "researchforge.yaml",
        "compliance/",
    ]
    found = []
    for c in candidates:
        if c.endswith("/"):
            if (repo_root / c.rstrip("/")).is_dir():
                found.append(c)
        else:
            if (repo_root / c).exists():
                found.append(c)
    return found or ["benchmarks/evaluate.py"]


def build_minimal_policy(
    source_note: str,
    repo_root: Path,
) -> str:
    """Generate a safe minimal policy.yaml without AI."""
    protected = _guess_protected_files(repo_root)
    protected_yaml = "\n".join(f"  - {p}" for p in protected)
    return _MINIMAL_POLICY_TEMPLATE.format(
        source_note=source_note,
        protected_files_yaml=protected_yaml,
    )


# ── AI generation ─────────────────────────────────────────────────────────────

_SYSTEM = """\
You are generating a ResearchForge policy.yaml file from one or more compliance
documents provided by the user's organization.

ResearchForge's policy.yaml controls:
  - protected_files: paths experiments can never modify
  - models.allowed_providers / denied_providers: AI provider allow/deny list
  - shipping.human_approval_required: whether a human must approve before shipping
  - security.secret_scan / dependency_scan / sbom / provenance: MUST be one of the
    exact strings: "required", "optional", or "disabled". NEVER use true/false.
    Use "required" when the document mandates the scan.
    Use "disabled" when it is explicitly prohibited.
    Use "optional" for everything else.
  - security.vulnerabilities.block_severity: severity levels that block shipping
  - network.default / allowed_domains: egress policy
  - data.pii_allowed / secrets_allowed / denied_data_paths: data boundaries
  - commands.allow / deny: command execution policy

RULES:
1. Read the documents carefully.  Extract every rule that maps to a PolicySpec field.
2. Add a YAML comment on every non-default value citing the source document and section.
3. Keep the YAML valid — every key must be a known PolicySpec field.
4. For security.secret_scan, security.dependency_scan, security.sbom, and
   security.provenance: always use the string "required", "optional", or
   "disabled" — NEVER booleans (true/false).
5. Never invent rules that are not in the documents.
5. If a field has no relevant rule, use the safe default.
6. Output ONLY the policy.yaml content — no explanation, no markdown fences.

Output format:
  version: 1
  # Source: <filename> § <section>
  protected_files:
    - ...
  models:
    ...
  (all remaining sections)
"""


def _build_prompt(docs: list[tuple[Path, str]], repo_root: Path) -> str:
    protected = _guess_protected_files(repo_root)
    sections = []
    for path, text in docs:
        rel = path.relative_to(repo_root) if path.is_relative_to(repo_root) else path.name
        sections.append(f"=== Document: {rel} ===\n{text}")

    return (
        "Generate a ResearchForge policy.yaml from the following compliance document(s).\n\n"
        f"Repository protected files detected: {protected}\n\n"
        + "\n\n".join(sections)
        + "\n\nNow output the complete policy.yaml:"
    )


def generate_policy_from_docs(
    docs: list[tuple[Path, str]],
    repo_root: Path,
    provider: AiProvider,
) -> str:
    """Use AI to generate policy.yaml from compliance documents."""
    prompt = _build_prompt(docs, repo_root)
    with purpose("policy_generation"):
        response = provider.generate(_SYSTEM, prompt)

    # Strip markdown fences if the model wrapped the output
    text = response.strip()
    if text.startswith("```"):
        lines = text.splitlines()
        start = next((i for i, line in enumerate(lines) if line.startswith("```")), 0) + 1
        end = next(
            (i for i in range(len(lines) - 1, start, -1) if lines[i].startswith("```")),
            len(lines),
        )
        text = "\n".join(lines[start:end])

    # Validate it parses as YAML before returning
    parsed = yaml.safe_load(text)
    if not isinstance(parsed, dict):
        raise ValueError("AI returned invalid YAML — falling back to minimal policy.")

    return text


def add_source_metadata(policy_yaml: str, docs: list[tuple[Path, str]]) -> str:
    """Prepend a header block listing the source documents."""
    names = ", ".join(p.name for p, _ in docs)
    header = textwrap.dedent(f"""\
        # ResearchForge policy — generated by `researchforge generate policy`
        # Source documents: {names}
        # Edit and re-run `researchforge compliance policy-validate` after changes.
        #
        """)
    return header + policy_yaml
